-- H2(로컬 확인용) 전용 스키마
-- db/migration/V1, V3 와 구조는 같고 H2가 못 읽는 문법만 바꿈.
--   - gen_random_uuid()                -> RANDOM_UUID()
--   - GENERATED ALWAYS AS (...) STORED -> GENERATED ALWAYS AS (...)   (H2는 STORED 미지원)
-- h2 프로필에서는 Flyway를 끄고 이 파일 + V2 시드 + schema-h2-v4-data.sql + schema-h2-v5-data.sql 을
-- sql.init 으로 돌린다.
-- 마이그레이션 추가하면 여기도 같이 맞춰야 함!
--
-- V4(프로젝트코드 형식 변경) 반영:
--   - year_code 는 새 코드(26-DSH-BOT-01) 앞 2자리에서 파생
--   - month_code 는 일반 컬럼. V2 시드는 옛 코드(P26110001)로 들어오므로
--     schema-h2-v4-data.sql 이 월을 채우고 코드를 변환한 뒤 제약을 건다.
--
-- V5(Kcode 제거 + No 추가) 반영:
--   - kcode / requires_partner_code 는 V2 시드가 값을 넣기 때문에 여기선 일단 만들고,
--     schema-h2-v5-data.sql 이 시드 적재 후 삭제한다.
--   - no 는 시드 적재 시 IDENTITY로 채워지고, v5-data 가 V5와 같은 순서로 번호를 다시 매긴 뒤
--     GENERATED ALWAYS + UNIQUE 로 잠근다.
-- ============================================================================

-- 같은 JVM에서 컨텍스트가 여러 번 뜨면(테스트) 인메모리 DB가 재사용되므로 먼저 지움
DROP TABLE IF EXISTS client;               -- V6 (테이블 생성/시드는 V6 파일을 그대로 실행)
DROP TABLE IF EXISTS project_audit_log;
DROP TABLE IF EXISTS direct_cost_item;
DROP TABLE IF EXISTS project;
DROP TABLE IF EXISTS admin_account;

CREATE TABLE admin_account (
    id            BIGSERIAL PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    display_name  VARCHAR(50)  NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE TABLE project (
    id                     UUID DEFAULT RANDOM_UUID() PRIMARY KEY,
    no                     BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    project_code           VARCHAR(20)  NOT NULL,
    kcode                  VARCHAR(20),                  -- V5에서 삭제 (시드 적재용)
    title                  VARCHAR(500) NOT NULL,
    project_type           VARCHAR(100),
    manager                VARCHAR(100),
    client_name            VARCHAR(200),
    client_manager         VARCHAR(100),
    revenue_amount         NUMERIC(15,2) NOT NULL DEFAULT 0,
    requires_partner_code  BOOLEAN NOT NULL DEFAULT FALSE, -- V5에서 삭제 (시드 적재용)
    year_code              VARCHAR(4)  GENERATED ALWAYS AS ('20' || SUBSTRING(project_code FROM 1 FOR 2)),
    month_code             VARCHAR(2),
    created_at             TIMESTAMP NOT NULL DEFAULT now(),
    updated_at             TIMESTAMP NOT NULL DEFAULT now()
);

CREATE INDEX idx_project_year_month ON project (year_code, month_code);
CREATE INDEX idx_project_kcode      ON project (kcode);

CREATE TABLE direct_cost_item (
    id            BIGSERIAL PRIMARY KEY,
    project_id    UUID NOT NULL REFERENCES project(id) ON DELETE CASCADE,
    category_code VARCHAR(30) NOT NULL,
    unit_price    NUMERIC(15,2),
    quantity      NUMERIC(15,2),
    days          NUMERIC(15,2),
    amount        NUMERIC(15,2) NOT NULL DEFAULT 0,
    note          VARCHAR(500),
    CONSTRAINT uq_direct_cost_item UNIQUE (project_id, category_code)
);

CREATE INDEX idx_direct_cost_item_project ON direct_cost_item (project_id);

-- V3__project_audit_log.sql
CREATE TABLE project_audit_log (
    id            BIGSERIAL PRIMARY KEY,
    project_id    UUID         NOT NULL,
    project_code  VARCHAR(20),
    action        VARCHAR(30)  NOT NULL,
    old_value     VARCHAR(500),
    new_value     VARCHAR(500),
    changed_by    VARCHAR(50)  NOT NULL,
    changed_at    TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE INDEX idx_audit_project    ON project_audit_log (project_id, changed_at DESC);
CREATE INDEX idx_audit_changed_at ON project_audit_log (changed_at DESC);
